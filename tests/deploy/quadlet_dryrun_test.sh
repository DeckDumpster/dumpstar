#!/usr/bin/env bash
# tier: T2
# covers: deploy/*.container deploy/units-lib.sh
# tests/deploy/quadlet_dryrun_test.sh — every deploy/*.container template is accepted by the quadlet
# of the podman version production runs (sp-mxinc0). Production's podman 4.9.3 rejected StopTimeout=,
# generated no dumpstar-prod.service, and the site went down. The version is pinned in
# deploy/prod-podman-version; quadlet of that version runs from the official podman image, so an
# unsupported key fails here naming the key, whatever the CI host's own podman is.
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

VERSION="$(tr -d '[:space:]' <"$REPO_DIR/deploy/prod-podman-version")"
IMAGE="quay.io/podman/stable:v${VERSION}"
# Templates to check: the repo's, or the directory given (the test's own negative control).
SRC="${1:-$REPO_DIR/deploy}"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$WORK/units"
n=0
for t in "$SRC"/*.container; do
	sed -e 's|{{INSTANCE}}|qtest|g' -e 's|{{PORT}}|8099|g' -e 's|{{VOLUME}}|dumpstar-qtest-data|g' \
		-e 's|{{SECRETS_DIR}}|%h/.config/dumpstar/qtest|g' -e 's|{{S3_PREFIX}}|qtest|g' \
		-e '/^Environment=DUMPSTAR_MCP_RESOURCE=/d' -e "s|{{REPO_DIR}}|$REPO_DIR|g" \
		"$t" >"$WORK/units/$(basename "$t" | sed 's/^dumpstar\.container$/dumpstar-qtest.container/')"
	n=$((n + 1))
done
[ "$n" -gt 0 ] || { echo "FAIL: no templates under $SRC"; exit 1; }

out="$(podman run --rm -v "$WORK/units:/units:ro,Z" -e QUADLET_UNIT_DIRS=/units "$IMAGE" \
	/usr/libexec/podman/quadlet -dryrun -user 2>&1)" || rc=$?
rc="${rc:-0}"
echo "$out"

if grep -q "unsupported key" <<<"$out" || [ "$rc" -ne 0 ]; then
	echo "FAIL: podman ${VERSION} quadlet rejects a template:"
	grep -E "unsupported key|converting" <<<"$out" || true
	exit 1
fi
for f in "$WORK"/units/*.container; do
	svc="$(basename "$f" .container).service"
	grep -q "^---${svc}---" <<<"$out" || { echo "FAIL: no ${svc} generated by podman ${VERSION}"; exit 1; }
done
echo "PASS: podman ${VERSION} quadlet generates a unit from each of $n templates"
